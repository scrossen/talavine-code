using System.Globalization;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace SwarmCore.Testing.PersonalMemoryEvals;

/// <summary>One scored check. Required checks gate the test; informational ones document known limits.</summary>
internal sealed record MemoryEvalCheck(string Name, bool Passed, bool Required = true, string? Detail = null);

/// <summary>The scored outcome of one eval for one app.</summary>
internal sealed class MemoryEvalResult
{
    public required string App { get; init; }
    public required string Eval { get; init; }
    public string Variant { get; init; } = "";
    public List<MemoryEvalCheck> Checks { get; init; } = [];
    public Dictionary<string, double> Metrics { get; init; } = new(StringComparer.Ordinal);
    public DateTimeOffset RanAtUtc { get; init; } = DateTimeOffset.UtcNow;

    public int RequiredTotal => Checks.Count(c => c.Required);
    public int RequiredPassed => Checks.Count(c => c.Required && c.Passed);
    public int InfoTotal => Checks.Count(c => !c.Required);
    public int InfoPassed => Checks.Count(c => !c.Required && c.Passed);
    public bool Passed => RequiredPassed == RequiredTotal;

    public void Check(string name, bool passed, string? detail = null) => Checks.Add(new(name, passed, true, passed ? null : detail));
    public void Note(string name, bool passed, string? detail = null) => Checks.Add(new(name, passed, false, detail));
    public void Metric(string name, double value) => Metrics[name] = value;

    [JsonIgnore]
    public IEnumerable<MemoryEvalCheck> FailedRequired => Checks.Where(c => c.Required && !c.Passed);

    /// <summary>Human-readable failure list for assertion messages.</summary>
    public string Describe()
        => $"{App}/{Eval}{(Variant.Length > 0 ? " [" + Variant + "]" : "")}: {RequiredPassed}/{RequiredTotal} required checks passed. Failed: "
           + string.Join("; ", FailedRequired.Select(c => c.Name + (c.Detail is null ? "" : " (" + c.Detail + ")")));
}

/// <summary>
/// Persists each result as JSON under TestResults/memory-evals/results and re-renders
/// TestResults/memory-evals/scorecard.md from every stored result (all apps, all runs' latest).
/// Set MEMORY_EVAL_RESULTS_DIR to write elsewhere. Writing never fails a test.
/// </summary>
internal static class MemoryEvalScorecard
{
    private static readonly JsonSerializerOptions Json = new(JsonSerializerDefaults.Web) { WriteIndented = true };
    private static readonly object Gate = new();

    public static string ResultsDirectory
    {
        get
        {
            var overridden = Environment.GetEnvironmentVariable("MEMORY_EVAL_RESULTS_DIR");
            if (!string.IsNullOrWhiteSpace(overridden)) return overridden;
            return Path.Combine(RepositoryRoot() ?? Path.GetTempPath(), "TestResults", "memory-evals");
        }
    }

    public static string ScorecardPath => Path.Combine(ResultsDirectory, "scorecard.md");

    public static void Record(MemoryEvalResult result)
    {
        try
        {
            lock (Gate)
            {
                var dir = Path.Combine(ResultsDirectory, "results");
                Directory.CreateDirectory(dir);
                var name = Safe($"{result.App}.{result.Eval}.{result.Variant}") + ".json";
                WriteWithRetry(Path.Combine(dir, name), JsonSerializer.Serialize(result, Json));
                WriteWithRetry(ScorecardPath, Render(Load(dir)));
            }
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or JsonException)
        {
            // Results are a report, not a gate: a locked file must not fail the eval.
        }
    }

    private static List<MemoryEvalResult> Load(string dir)
    {
        var list = new List<MemoryEvalResult>();
        foreach (var file in Directory.EnumerateFiles(dir, "*.json"))
        {
            try
            {
                var item = JsonSerializer.Deserialize<MemoryEvalResult>(File.ReadAllText(file), Json);
                if (item is not null) list.Add(item);
            }
            catch (Exception ex) when (ex is IOException or JsonException) { }
        }
        return list;
    }

    private static readonly string[] EvalOrder =
    [
        "planted-recall", "preference-adherence", "distractor-resistance", "time-sensitive",
        "poisoning-resistance", "isolation", "incognito-and-controls", "live-benefit",
    ];

    private static readonly string[] AppOrder = ["core", "talavine", "crm", "swarmcode"];

    internal static string Render(IReadOnlyList<MemoryEvalResult> results)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Personal memory eval scorecard");
        sb.AppendLine();
        sb.AppendLine("Generated by the shared eval kit (`SwarmCore/Testing/PersonalMemoryEvals`). Deterministic evals drive each app's real");
        sb.AppendLine("host wiring with a scripted model; `live-benefit` runs only when opted in. Required checks gate the tests;");
        sb.AppendLine("informational checks record known limits. Each row is the latest run of that eval.");
        sb.AppendLine();
        sb.AppendLine($"Last updated: {DateTimeOffset.UtcNow.ToString("yyyy-MM-dd HH:mm:ss", CultureInfo.InvariantCulture)} UTC");
        sb.AppendLine();

        var ordered = results
            .OrderBy(r => Index(EvalOrder, r.Eval)).ThenBy(r => r.Eval, StringComparer.Ordinal)
            .ThenBy(r => Index(AppOrder, r.App)).ThenBy(r => r.App, StringComparer.Ordinal)
            .ThenBy(r => r.Variant, StringComparer.Ordinal)
            .ToList();

        sb.AppendLine("## Summary");
        sb.AppendLine();
        sb.AppendLine("| App | Evals | Required checks passed | % | Informational passed |");
        sb.AppendLine("|---|---|---|---|---|");
        foreach (var app in ordered.GroupBy(r => r.App).OrderBy(g => Index(AppOrder, g.Key)))
        {
            var req = app.Sum(r => r.RequiredTotal);
            var ok = app.Sum(r => r.RequiredPassed);
            sb.AppendLine($"| {app.Key} | {app.Count()} | {ok}/{req} | {Pct(ok, req)} | {app.Sum(r => r.InfoPassed)}/{app.Sum(r => r.InfoTotal)} |");
        }
        sb.AppendLine();

        sb.AppendLine("## Per eval");
        sb.AppendLine();
        sb.AppendLine("| Eval | Variant | App | Result | Required | % | Info | Key metrics | Ran (UTC) |");
        sb.AppendLine("|---|---|---|---|---|---|---|---|---|");
        foreach (var r in ordered)
        {
            var metrics = string.Join(", ", r.Metrics.OrderBy(m => m.Key, StringComparer.Ordinal).Select(m => $"{m.Key}={Format(m.Value)}"));
            sb.AppendLine($"| {r.Eval} | {Escape(r.Variant)} | {r.App} | {(r.Passed ? "PASS" : "FAIL")} | {r.RequiredPassed}/{r.RequiredTotal} | {Pct(r.RequiredPassed, r.RequiredTotal)} | {r.InfoPassed}/{r.InfoTotal} | {Escape(metrics)} | {r.RanAtUtc.UtcDateTime.ToString("yyyy-MM-dd HH:mm", CultureInfo.InvariantCulture)} |");
        }
        sb.AppendLine();

        var notes = ordered.SelectMany(r => r.Checks.Where(c => !c.Passed).Select(c => (r, c))).ToList();
        sb.AppendLine("## Failed and informational checks");
        sb.AppendLine();
        if (notes.Count == 0) sb.AppendLine("None.");
        foreach (var (r, c) in notes)
            sb.AppendLine($"- {(c.Required ? "**FAILED**" : "info")} {r.App} / {r.Eval}{(r.Variant.Length > 0 ? " [" + r.Variant + "]" : "")}: {Escape(c.Name)}{(c.Detail is null ? "" : " — " + Escape(c.Detail))}");
        return sb.ToString();
    }

    private static int Index(string[] order, string value) { var i = Array.IndexOf(order, value); return i < 0 ? order.Length : i; }
    private static string Pct(int ok, int total) => total == 0 ? "n/a" : (100.0 * ok / total).ToString("0.#", CultureInfo.InvariantCulture) + "%";
    private static string Format(double v) => v == Math.Floor(v) && Math.Abs(v) < 1e9 ? v.ToString("0", CultureInfo.InvariantCulture) : v.ToString("0.###", CultureInfo.InvariantCulture);
    private static string Escape(string value) => value.Replace("|", "\\|", StringComparison.Ordinal).Replace("\n", " ", StringComparison.Ordinal);
    private static string Safe(string value) => string.Concat(value.Select(ch => char.IsLetterOrDigit(ch) || ch is '-' or '.' ? ch : '_'));

    private static void WriteWithRetry(string path, string content)
    {
        for (var attempt = 0; ; attempt++)
        {
            try
            {
                var tmp = path + "." + Environment.ProcessId.ToString(CultureInfo.InvariantCulture) + ".tmp";
                File.WriteAllText(tmp, content);
                File.Move(tmp, path, overwrite: true);
                return;
            }
            catch (IOException) when (attempt < 10)
            {
                Thread.Sleep(50 * (attempt + 1));
            }
            catch (UnauthorizedAccessException) when (attempt < 10)
            {
                Thread.Sleep(50 * (attempt + 1));
            }
        }
    }

    /// <summary>The checkout root: the nearest ancestor with AGENTS.md and a SwarmCore folder.</summary>
    private static string? RepositoryRoot()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir is not null)
        {
            if (File.Exists(Path.Combine(dir.FullName, "AGENTS.md")) && Directory.Exists(Path.Combine(dir.FullName, "SwarmCore")))
                return dir.FullName;
            dir = dir.Parent;
        }
        return null;
    }
}
